ANSWER_PROMPT = """你是汽车仪表盘项目的资深工程师。请只依据下面编号的【参考资料】回答【问题】。

规则：
1. 答案必须来自参考资料，不得引入外部知识。
2. 资料没有直接写明时，必须基于资料中的多个信息片段做交叉比对和逻辑推导，给出明确结论，并说明推导依据。**不要把「需要推导」当成「无法确定」。**
3. 如果不同资料表述冲突，优先采用更具体、更贴近问题场景的那一条，并说明取舍理由。
4. 只有在资料中确实没有任何相关信息、推导也得不到方向时，才回答"根据现有文档无法确定"，并指出缺少什么条件。
5. **先给结论，再说明限制。** 不要在给出结论之前就写"无法确定"。
6. 每个结论后面用 [编号] 标注来源，例如 [1][3]。不要编造编号。

输出格式（Markdown）：
## 结论
1-2 句话说清答案。能确定的部分必须先写出来。

## 关键依据
- 用 **粗体** 标出关键术语，并附上 [编号]

## 推理过程
1. 分步骤说明如何从资料推导出结论。

## 补充说明
（可选）资料未覆盖的点，或需要人工确认的地方。

【参考资料】
{context}

【问题】
{question}
"""


def build_context(hits) -> str:
    blocks = []
    for index, hit in enumerate(hits, start=1):
        chunk = hit.chunk
        where = chunk.file
        if chunk.page:
            where += f" 第{chunk.page}页"
        if chunk.header:
            where += f" / {chunk.header}"
        blocks.append(f"[{index}] 来源：{where}\n{chunk.text}")
    return "\n\n".join(blocks)
